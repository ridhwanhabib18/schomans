    private const string Banner = "Generated by tools/SchoMans.DocGen from the code. Do not edit by hand; change the code and run `dotnet run --project tools/SchoMans.DocGen`.";

    // Columns every entity has through BaseEntity; the ERD leaves them out like the hand-written one did.
    private static readonly HashSet<string> BaseColumns = ["CreatedAt", "UpdatedAt", "IsDeleted", "RowVersion", "Id"];

    private static List<IEntityType> Entities(AppDbContext db) => db.Model.GetEntityTypes()
        .Where(e => !e.IsOwned() && !e.HasSharedClrType)
        .OrderBy(e => e.ClrType.Name, StringComparer.Ordinal)
        .ToList();

    /// <summary>The whole model in one diagram.</summary>
    public static string Erd(AppDbContext db) => Erd(Entities(db), withBanner: true);

    /// <summary>One diagram per domain (the namespace of the entity); an entity of another domain appears only as the end of a relation.</summary>
    public static IReadOnlyList<(string Domain, string Diagram)> ErdByDomain(AppDbContext db) => Entities(db)
        .GroupBy(e => e.ClrType.Namespace!.Split('.').Last())
        .OrderBy(g => g.Key, StringComparer.Ordinal)
        .Select(g => (g.Key, Erd(g.ToList(), withBanner: false)))
        .ToList();

    private static string Erd(IReadOnlyList<IEntityType> entities, bool withBanner)
    {
        var text = new StringBuilder();
        if (withBanner)
        {
            text.AppendLine($"%% {Banner}");
            text.AppendLine("%% Every entity also has Id, CreatedAt, UpdatedAt, IsDeleted and RowVersion (omitted here); a deleted row stays in the table (soft delete).");
        }

        text.AppendLine("erDiagram");

        foreach (var entity in entities)
        {
            foreach (var key in entity.GetDeclaredForeignKeys().OrderBy(k => k.Properties[0].Name, StringComparer.Ordinal))
            {
                if (key.PrincipalEntityType.IsOwned() || key.PrincipalEntityType.HasSharedClrType)
                {
                    continue;
                }

                var principal = key.PrincipalEntityType.ClrType.Name;
                var dependent = entity.ClrType.Name;
                var left = key.IsRequired ? "||" : "|o";
                var right = key.IsUnique ? "o|" : "o{";
                var label = key.DependentToPrincipal?.Name ?? key.Properties[0].Name;
                text.AppendLine($"  {principal} {left}--{right} {dependent} : \"{label}\"");
            }
        }

        foreach (var entity in entities)
        {
            text.AppendLine($"  {entity.ClrType.Name} {{");
            var primaryKey = entity.FindPrimaryKey()?.Properties.Select(p => p.Name).ToHashSet() ?? [];
            var foreignKeys = entity.GetForeignKeys().SelectMany(k => k.Properties).Select(p => p.Name).ToHashSet();
            text.AppendLine("    guid Id PK");
            foreach (var property in entity.GetDeclaredProperties().Where(p => !BaseColumns.Contains(p.Name)).OrderBy(p => p.Name, StringComparer.Ordinal))
            {
                var keys = new List<string>();
                if (primaryKey.Contains(property.Name))
                {
                    keys.Add("PK");
                }

                if (foreignKeys.Contains(property.Name))
                {
                    keys.Add("FK");
                }

                text.AppendLine($"    {TypeOf(property)} {property.Name}{(keys.Count > 0 ? " " + string.Join(",", keys) : string.Empty)}");
            }

            text.AppendLine("  }");
        }

        return text.ToString();
    }

    private static string TypeOf(IProperty property)
    {
        var type = Nullable.GetUnderlyingType(property.ClrType) ?? property.ClrType;
        if (type.IsEnum)
        {
            return "enum";
        }

        return type.Name switch
        {
            "Guid" => "guid",
            "String" => "string",
            "Int32" => "int",
            "Int64" => "long",
            "Decimal" => "decimal",
            "Double" => "double",
            "Boolean" => "bool",
            "DateTimeOffset" or "DateTime" => "datetime",
            "DateOnly" => "date",
            "TimeOnly" or "TimeSpan" => "time",
            "Byte[]" => "bytes",
            _ => type.Name.ToLowerInvariant(),
        };
    }

    public static string ApiReference(IReadOnlyList<Operation> operations)
    {
        var text = new StringBuilder();
        text.AppendLine("# API reference");
        text.AppendLine();
        text.AppendLine($"<!-- {Banner} -->");
        text.AppendLine();
        text.AppendLine($"{operations.Count} operations, read from the endpoints the API registers. Every route is under the base address of the API; list endpoints take `page` and `pageSize` (at most 100) and return `PagedResult<T>`. Errors are ProblemDetails.");
        text.AppendLine("The interactive reference (Scalar) is at `/scalar` in the Development and Demo environments. **Auth** is the first layer of the two-layer authorization: the role policy of the endpoint; the ownership check in the Application layer comes on top of it.");

        foreach (var group in operations.GroupBy(o => o.Group))
        {
            text.AppendLine();
            text.AppendLine($"## {group.Key}");
            text.AppendLine();
            text.AppendLine("| Method | Route | Operation | Auth | Request | Response |");
            text.AppendLine("| --- | --- | --- | --- | --- | --- |");
            foreach (var operation in group)
            {
                var auth = operation.Anonymous ? "anonymous" : operation.Policies.Count == 0 ? "signed in" : string.Join(" + ", operation.Policies);
                var rate = operation.RateLimit is null ? string.Empty : $" (rate limit: {operation.RateLimit})";
                text.AppendLine($"| {operation.Method} | `{operation.Route}` | {operation.Name} | {auth}{rate} | {Cell(operation.Request)} | {Cell(operation.Response)} |");
            }
        }

        return text.ToString();
    }

    /// <summary>One row per group of endpoints: its base path, how many operations, and the roles that can call at least one of them.</summary>
    public static string ApiGroups(IReadOnlyList<Operation> operations, IReadOnlyList<PolicyInfo> policies)
    {
        var text = new StringBuilder();
        text.AppendLine("| Group | Base path | Operations | Roles (any operation) |");
        text.AppendLine("| --- | --- | ---: | --- |");
        foreach (var group in operations.GroupBy(o => o.Group))
        {
            var routes = group.Select(o => o.Route.Trim('/').Split('/')).ToList();
            var common = routes[0].TakeWhile((part, i) => routes.All(r => r.Length > i && r[i] == part)).ToList();
            var allowed = group.Select(o => ApiModel.AllowedRoles(o, policies)).ToList();
            var roles = allowed.Any(a => a is null)
                ? "anonymous and signed-in users"
                : string.Join(", ", AppRoles.All.Where(role => allowed.Any(a => a!.Contains(role))));
            text.AppendLine($"| {group.Key} | `/{string.Join('/', common)}` | {group.Count()} | {roles} |");
        }

        return text.ToString();
    }

    public static string AuthorizationMatrix(IReadOnlyList<Operation> operations, IReadOnlyList<PolicyInfo> policies)
    {
        var text = new StringBuilder();
        text.AppendLine("# Authorization matrix");
        text.AppendLine();
        text.AppendLine($"<!-- {Banner} -->");
        text.AppendLine();
        text.AppendLine("Which role may call which endpoint, from the policies registered on the endpoints. This is the first layer (the role policy); a second layer in the Application layer then checks ownership, for example that a parent sees only their own children. `any` means anonymous, `signed in` means any signed-in user.");
        text.AppendLine();
        text.AppendLine("## Policies");
        text.AppendLine();
        text.AppendLine("| Policy | Roles |");
        text.AppendLine("| --- | --- |");
        foreach (var policy in policies)
        {
            text.AppendLine($"| {policy.Name} | {(policy.Roles.Count == 0 ? "any signed-in user" : string.Join(", ", policy.Roles))} |");
        }

        text.AppendLine();
        text.AppendLine("## Endpoints");
        text.AppendLine();
        text.AppendLine("| Method | Route | " + string.Join(" | ", AppRoles.All) + " |");
        text.AppendLine("| --- | --- | " + string.Join(" | ", AppRoles.All.Select(_ => ":---:")) + " |");
        foreach (var operation in operations)
        {
            var allowed = ApiModel.AllowedRoles(operation, policies);
            var cells = AppRoles.All.Select(role => allowed is null ? "any" : allowed.Contains(role) ? "yes" : "-");
            text.AppendLine($"| {operation.Method} | `{operation.Route}` | {string.Join(" | ", cells)} |");
        }

        return text.ToString();
    }

    public static string JobsAndRealtime() =>
        "# Background jobs and real-time events\n\n" + $"<!-- {Banner} -->\n\n" + JobsAndRealtimeBody("##");

    /// <summary>The jobs and the hubs as sections; <paramref name="level"/> is the heading marker of a section.</summary>
    public static string JobsAndRealtimeBody(string level)
    {
        var text = new StringBuilder();
        text.AppendLine($"{level} Recurring jobs (Hangfire)");
        text.AppendLine();
        text.AppendLine("Registered once at start-up by `JobsSetup.RegisterRecurringJobs`; the jobs dashboard is `/hangfire` (admin staff and the principal, not routed on the public internet).");
        text.AppendLine();
        text.AppendLine("| Id | Job | Schedule (cron) | Time zone |");
        text.AppendLine("| --- | --- | --- | --- |");
        foreach (var job in CapturedJobs())
        {
            text.AppendLine($"| `{job.Id}` | {job.Type} | `{job.Cron}` | {job.Zone} |");
        }

        text.AppendLine();
        text.AppendLine($"{level} SignalR hubs");
        text.AppendLine();
        text.AppendLine("Both hubs need a signed-in user (the access token is sent as the `access_token` query value of the WebSocket request).");
        foreach (var hub in typeof(NotificationHub).Assembly.GetTypes().Where(t => typeof(Hub).IsAssignableFrom(t) && !t.IsAbstract).OrderBy(t => t.Name, StringComparer.Ordinal))
        {
            var path = hub.GetField("Path", BindingFlags.Public | BindingFlags.Static)?.GetRawConstantValue();
            text.AppendLine();
            text.AppendLine($"{level}# {hub.Name} (`{path}`)");
            text.AppendLine();
            var events = hub.GetFields(BindingFlags.Public | BindingFlags.Static).Where(f => f.IsLiteral && f.Name.EndsWith("Event", StringComparison.Ordinal)).OrderBy(f => f.Name, StringComparer.Ordinal).ToList();
            text.AppendLine("Events the server sends: " + (events.Count == 0 ? "none" : string.Join(", ", events.Select(f => $"`{f.GetRawConstantValue()}`"))) + ".");
            var methods = hub.GetMethods(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly).Where(m => !m.IsSpecialName).OrderBy(m => m.Name, StringComparer.Ordinal).ToList();
            text.AppendLine();
            text.AppendLine("Methods the client may call: " + (methods.Count == 0 ? "none" : string.Join(", ", methods.Select(m => $"`{m.Name}({string.Join(", ", m.GetParameters().Select(p => p.ParameterType.Name + " " + p.Name))})`"))) + ".");
        }

        return text.ToString();
    }

    /// <summary>
    /// Runs the real registration against a stand-in manager that only writes down what it is told, so the table is the schedule the
    /// API really registers.
    /// </summary>
    private static IReadOnlyList<(string Id, string Type, string Cron, string Zone)> CapturedJobs()
    {
        var manager = new CapturingRecurringJobManager();
        var services = new ServiceCollection();
        services.AddSingleton<IRecurringJobManager>(manager);
        services.Configure<JobsOptions>(options => options.Enabled = true);
        services.Configure<SchoolOptions>(options => options.TimeZone = "Asia/Jakarta");
        JobsSetup.RegisterRecurringJobs(services.BuildServiceProvider());
        return manager.Jobs;
    }

    private sealed class CapturingRecurringJobManager : IRecurringJobManager
    {
        public List<(string Id, string Type, string Cron, string Zone)> Jobs { get; } = [];

        public void AddOrUpdate(string recurringJobId, Job job, string cronExpression, RecurringJobOptions options) =>
            Jobs.Add((recurringJobId, job.Type.Name, cronExpression, options.TimeZone.Id == TimeZoneInfo.Utc.Id ? "UTC" : options.TimeZone.Id));

        public void Trigger(string recurringJobId) => throw new NotSupportedException();

        public void RemoveIfExists(string recurringJobId) => throw new NotSupportedException();
    }

    private static string Cell(string? value) => value is null ? string.Empty : $"`{value}`";
}
